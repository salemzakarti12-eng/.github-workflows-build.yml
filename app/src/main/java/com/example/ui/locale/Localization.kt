fun getAppStrings(language: String): AppStrings {
    return when (language.lowercase()) {
        "ar" -> ArabicStrings
        "zh" -> ChineseStrings
        "ja" -> JapaneseStrings
        "fr" -> FrenchStrings
        "es" -> SpanishStrings
        "tr" -> TurkishStrings
        "ur" -> UrduStrings
        "ru" -> RussianStrings
        "pt" -> PortugueseStrings
        else -> EnglishStrings
    }
}

fun isRtlLanguage(language: String): Boolean {
    return language.equals("ar", ignoreCase = true) ||
        language.equals("ur", ignoreCase = true)
}

