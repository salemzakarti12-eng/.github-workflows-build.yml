fun getAppStrings(language: String): AppStrings {
    return if (language.equals("ar", ignoreCase = true)) {
        ArabicStrings
    } else {
        EnglishStrings
    }
}

val LocalAppLanguage = staticCompositionLocalOf { "en" }
val LocalAppStrings = staticCompositionLocalOf { EnglishStrings }

object AppLanguageManager {
    const val PREF_KEY_LANGUAGE = "app_language"
    const val LANG_EN = "en"
    const val LANG_AR = "ar"
}

@Composable
@ReadOnlyComposable
fun appStrings(): AppStrings = LocalAppStrings.current
