    fun translate(rawCategory: String, language: String): String {
        val trimmed = rawCategory.trim()
        if (trimmed.isEmpty()) return rawCategory

        val langKey = language.lowercase().take(2)
        val labels = labelsByLang[langKey] ?: labelsByLang["en"]!!

        // Preserve category separators like "|", "-", "•", ":" while translating each segment
        val separators = listOf(" | ", "|", " - ", " • ", ": ")
        for (sep in separators) {
            if (trimmed.contains(sep)) {
                return trimmed.split(sep)
                    .joinToString(sep) { part -> translateSegment(part.trim(), labels) }
            }
        }

        return translateSegment(trimmed, labels)
    }

