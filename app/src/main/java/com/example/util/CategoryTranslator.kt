    fun translate(rawCategory: String, isAr: Boolean): String {
        if (!isAr) return rawCategory
        val trimmed = rawCategory.trim()
        if (trimmed.isEmpty()) return rawCategory

        // Keep native Arabic category names as-is
        if (trimmed.any { it in '\u0600'..'\u06FF' }) return trimmed

        // Exact match check (also handles "AR: Sports" or "SA | Movies" prefixes)
        exactMap[trimmed.lowercase()]?.let { return it }

        var result = trimmed
            .replace(Regex("^(AR|ARB|SA|KSA|UAE|KW|QA|BH|OM|EG|SY|LB|JO|IQ|MA|DZ|TN)\\s*[:|\\-/>]+\\s*", RegexOption.IGNORE_CASE)) { match ->
                val code = match.groupValues[1].uppercase()
                val prefix = when (code) {
                    "AR", "ARB" -> "عربي"
                    "SA", "KSA" -> "السعودية"
                    "UAE" -> "الإمارات"
                    "KW" -> "الكويت"
                    "QA" -> "قطر"
                    "BH" -> "البحرين"
                    "OM" -> "عُمان"
                    "EG" -> "مصر"
                    "SY" -> "سوريا"
                    "LB" -> "لبنان"
                    "JO" -> "الأردن"
                    "IQ" -> "العراق"
                    "MA" -> "المغرب"
                    "DZ" -> "الجزائر"
                    "TN" -> "تونس"
                    else -> code
                }
                "$prefix • "
            }

        for ((pattern, arabic) in tokenReplacements) {
            result = result.replace(Regex(pattern, RegexOption.IGNORE_CASE), arabic)
        }
        return result
    }
